// Local browser QA: node tests/public-service-ui.mjs (requires running dev server).
import assert from 'node:assert/strict';
import { mkdirSync, readFileSync } from 'node:fs';
import { randomUUID } from 'node:crypto';
import pg from 'pg';
import { loadProjectEnv } from '../scripts/load-env.mjs';
import { chromium } from '@playwright/test';
loadProjectEnv();
const base = process.env.TEST_BASE_URL || JSON.parse(readFileSync('.local/server.json', 'utf8')).url;
if (!['localhost','127.0.0.1'].includes(new URL(base).hostname)) throw Error('Local browser test only.');
if (!['localhost','127.0.0.1'].includes(new URL(process.env.DATABASE_URL).hostname)) throw Error('Local database only.');
const db = new pg.Client({ connectionString: process.env.DATABASE_URL });
await db.connect();
const email = `support-browser-${randomUUID()}@example.test`;
const directory = '.local/public-service-2026-10-22';
mkdirSync(directory, { recursive: true });
const browser = await chromium.launch({ headless: true });
let count = 0;
const check = (condition, label) => { assert.ok(condition, label); count++; };
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(base, { waitUntil: 'networkidle' });
  check((await page.title()).includes('각자ON'), 'home title');
  check(await page.locator('#auth-form').isVisible(), 'first screen auth');
  check(await page.locator('#login-overview details').count() === 5, 'five FAQ questions');
  check(await page.getByText('서비스 이해를 위한 예시', { exact: true }).count() === 1, 'example label');
  check(await page.locator('a[href="/privacy"]').count() > 0, 'public privacy link');
  await page.screenshot({ path: `${directory}/desktop-home.png`, fullPage: true });
  await page.setViewportSize({ width: 375, height: 812 });
  await page.goto(base, { waitUntil: 'networkidle' });
  check(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), 'mobile no horizontal overflow');
  check(await page.locator('[class*="mobileStart"]').count() === 0, 'no fixed CTA over login');
  await page.locator('#intro-faq-title').scrollIntoViewIfNeeded();
  await page.locator('[class*="mobileStart"] button').waitFor({ state: 'visible' });
  check(await page.locator('[class*="mobileStart"] button').isVisible(), 'fixed CTA after login scrolls away');
  await page.screenshot({ path: `${directory}/mobile-intro.png`, fullPage: false });
  await page.locator('[class*="mobileStart"] button').click();
  await page.waitForFunction(() => document.querySelector('#auth-form')?.contains(document.activeElement));
  check(await page.evaluate(() => document.querySelector('#auth-form')?.contains(document.activeElement)), 'CTA returns focus');
  await page.goto(`${base}/faq`, { waitUntil: 'networkidle' });
  await page.locator('details').nth(3).locator('summary').click();
  check((await page.locator('details').nth(3).innerText()).includes('담당자'), 'FAQ accurately states assigned access');
  await page.screenshot({ path: `${directory}/mobile-faq.png`, fullPage: true });
  await page.goto(`${base}/contact?type=privacy`, { waitUntil: 'networkidle' });
  check(await page.getByRole('button', { name: '문의 유형 · 개인정보·삭제 요청', exact: true }).count() === 1, 'privacy request preselected');
  check(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), 'contact no horizontal overflow');
  await page.screenshot({ path: `${directory}/mobile-contact.png`, fullPage: true });
  await page.locator('input[name="email"]').fill(email);
  await page.locator('textarea[name="content"]').fill('브라우저 검사에서 작성한 합성 삭제 요청입니다. 실제 사용자 자료가 아닙니다.');
  await page.locator('input[name="consent"]').check();
  await page.getByRole('button', { name: '문의 접수하기', exact: true }).click();
  await page.getByRole('heading', { name: '문의가 접수됐어요' }).waitFor();
  check(await page.getByText(email, { exact: true }).count() === 1, 'saved receipt email');
  const inquiry = (await db.query('select id,type from support_inquiries where email=$1', [email])).rows[0];
  check(inquiry?.type === 'privacy', 'browser form really saved selected inquiry');
  check((await page.locator('[role="status"]').innerText()).includes(inquiry.id), 'receipt corresponds to DB record');
  await page.screenshot({ path: `${directory}/mobile-contact-success.png`, fullPage: true });
  await page.goto(`${base}/privacy`, { waitUntil: 'networkidle' });
  check(await page.getByRole('heading', { name: '개인정보 처리방침', exact: true }).count() === 1, 'privacy accessible');
  const analytics = page.getByRole('checkbox', { name: /선택 통계 수집/ });
  check(!await analytics.isChecked(), 'optional analytics defaults off');
  await analytics.check(); check(await analytics.isChecked(), 'explicit opt-in control');
  await analytics.uncheck(); check(!await analytics.isChecked(), 'consent can be revoked');
  check(await page.locator('script[src*="googletagmanager"]').count() === 0, 'no GA tag without production configuration');
  await page.screenshot({ path: `${directory}/mobile-privacy.png`, fullPage: true });
  await page.goto(`${base}/missing-public-service-page`, { waitUntil: 'networkidle' });
  check(await page.getByRole('link', { name: '홈으로', exact: true }).count() >= 1, '404 public home link');
  const login = await page.request.post(`${base}/api/auth`, { headers: { Origin: base }, data: { action: 'login', email: 'admin@gakja.test', password: process.env.TEST_ACCOUNT_PASSWORD } });
  check(login.ok(), 'admin browser authentication');
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto(`${base}/admin/inquiries`, { waitUntil: 'networkidle' });
  const row = page.getByRole('region', { name: '개인정보·삭제 요청 문의' }).filter({ hasText: email });
  await row.waitFor();
  await row.getByRole('button', { name: /^처리 상태 ·/ }).click();
  await row.getByRole('option', { name: '확인 중', exact: true }).click();
  await row.locator('textarea').fill('합성 문의의 처리 상태 검증');
  await row.getByRole('button', { name: '처리 내역 저장' }).click();
  await row.getByText('처리 상태를 저장했어요.').waitFor();
  check((await db.query('select status from support_inquiries where id=$1', [inquiry.id])).rows[0].status === 'in_progress', 'admin UI persists inquiry state');
  await page.screenshot({ path: `${directory}/desktop-admin-inquiries.png`, fullPage: true });
  check(errors.length === 0, `no browser errors: ${errors.join('; ')}`);
  console.log(`Public browser QA: ${count} checks passed. Screenshots: ${directory}`);
} finally {
  await browser.close();
  await db.query("delete from audit_logs where action='support.inquiry.updated' and data->>'inquiryId' in (select id::text from support_inquiries where email=$1)", [email]);
  await db.query('delete from support_inquiries where email=$1', [email]);
  await db.end();
}
