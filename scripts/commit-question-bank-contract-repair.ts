import dotenv from 'dotenv';
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { loadInterviewContextAt } from '../server/data/load-interview-context';
import { activateReviewedObjectiveContracts, type FullStudentAnalysis, type TargetStudentAnalysis } from '../server/data/full-student-analysis';
import { projectPreparedActivities } from '../server/data/prepared-activities';
import { createStudentObjectiveCandidates } from '../server/question-objective';
import { loadQuestionBank } from '../server/data/prepared-question-bank';
import { loadApprovedRecoveryVariants } from '../server/data/approved-recovery-variants';
import type { RecordedTurn } from '../server/protocol';

// This resumes publication only. It does not import a model or invoke a provider.
dotenv.config({ path: '.env.local', quiet: true });
const file = 'artifacts/question-bank-contract-repair.json';
const report = JSON.parse(await readFile(file, 'utf8'));
if (!report.stagedRevisionPath || !report.newBankKey || !report.recovery?.identity) throw new Error('REPAIR_STAGE_NOT_COMPLETE');
const context = await loadInterviewContextAt(process.cwd());
if (context.errors.length) throw new Error('CONTEXT_NOT_READY');
const stagedBytes = await readFile(report.stagedRevisionPath);
const staged = JSON.parse(stagedBytes.toString('utf8')) as { common: FullStudentAnalysis; target: TargetStudentAnalysis };
const updated = structuredClone(context);
updated.targetAnalysis = staged.target;
const entry = updated.manifest.files.find(file => file.role === 'fullStudentAnalysis');
if (!entry) throw new Error('ANALYSIS_MANIFEST_ENTRY_MISSING');
entry.path = report.stagedRevisionPath.replace(/\\/gu, '/');
entry.sha256 = createHash('sha256').update(stagedBytes).digest('hex');
Object.assign(updated.manifest.recordIds, { targetAnalysisRevision: staged.target.revision, targetAnalysisContentSha256: staged.target.contentSha256 });
updated.preparedActivities = projectPreparedActivities(updated, staged.common);
updated.studentObjectives = createStudentObjectiveCandidates(updated, updated.preparedActivities);
const bank = await loadQuestionBank(updated);
if (!bank || bank.key !== report.newBankKey) throw new Error('STAGED_BANK_NOT_READY');
const motive = bank.slots.flatMap(slot => slot.candidates).find(candidate => candidate.draft.commonApproval?.moduleId === 'common-major-selection-motive');
if (!motive) throw new Error('STAGED_MOTIVE_NOT_READY');
const original = { id: 'offline-recovery-readiness', parentMainQuestionId: 'offline-recovery-readiness', questionKind: 'main', questionText: motive.draft.questionText, evidenceIds: motive.draft.evidenceIds, metadata: motive.draft } as unknown as RecordedTurn;
if (!(await loadApprovedRecoveryVariants(updated, original)).length) throw new Error('STAGED_RECOVERY_NOT_READY');
if (context.targetAnalysis?.revision !== staged.target.revision) await activateReviewedObjectiveContracts(context, report.stagedRevisionPath);
const committed = await loadInterviewContextAt(process.cwd());
if (committed.errors.length || (await loadQuestionBank(committed))?.key !== bank.key) throw new Error('COMMITTED_BANK_NOT_READY');
report.resumedWithoutProviderCalls = true;
report.activated = true;
report.activationCompletedAt = new Date().toISOString();
report.previousFailure = report.failure;
delete report.failure;
await writeFile(file, JSON.stringify(report, null, 2), { mode: 0o600 });
console.log(JSON.stringify({ activated: true, bankKey: bank.key, approvedQuestions: bank.slots.reduce((n, slot) => n + slot.candidates.length, 0), quarantineCount: bank.slots.filter(slot => slot.quarantine).length, recoveryVariantsReady: true, providerCalls: 0 }));
