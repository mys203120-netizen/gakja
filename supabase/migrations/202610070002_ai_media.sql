-- Private AI request lifecycle and bounded daily usage, separate from message text.
alter table chat_messages add column if not exists request_id text;
alter table chat_messages add column if not exists status text not null default 'completed';
alter table chat_messages add column if not exists position bigint generated by default as identity;
create index if not exists chat_messages_order_idx on chat_messages(thread_id,position);
create unique index if not exists chat_messages_request_idx on chat_messages(thread_id,request_id,role) where request_id is not null;
alter table chat_threads add column if not exists request_id text;
create unique index if not exists chat_threads_request_idx on chat_threads(student_id,request_id) where request_id is not null;
alter table interview_sessions add column if not exists request_id text;
create unique index if not exists interview_sessions_request_idx on interview_sessions(student_id,request_id) where request_id is not null;
create table if not exists ai_usage_logs (
  id uuid primary key default gen_random_uuid(), student_id uuid not null references profiles(id),
  feature text not null, model text not null, prompt_version text not null, context_id text,
  status text not null default 'pending', input_tokens int not null default 0, output_tokens int not null default 0,
  created_at timestamptz not null default now()
);
create index if not exists ai_usage_daily_idx on ai_usage_logs(student_id,created_at);
alter table ai_usage_logs enable row level security;

-- Private media uses the authenticated student's JWT, never a public URL.
do $$
begin
  if to_regclass('storage.buckets') is not null and to_regprocedure('auth.uid()') is not null then
    execute 'insert into storage.buckets(id,name,public,file_size_limit,allowed_mime_types) values(''student-media'',''student-media'',false,20971520,array[''video/webm'',''video/mp4'',''audio/webm'',''audio/mp4'',''audio/mpeg'',''audio/wav'',''audio/x-wav'',''audio/ogg'']) on conflict(id) do update set public=false';
    execute 'drop policy if exists student_media_read on storage.objects';
    execute 'create policy student_media_read on storage.objects for select to authenticated using (bucket_id=''student-media'' and (storage.foldername(name))[1]=auth.uid()::text)';
    execute 'drop policy if exists student_media_upload on storage.objects';
    execute 'create policy student_media_upload on storage.objects for insert to authenticated with check (bucket_id=''student-media'' and (storage.foldername(name))[1]=auth.uid()::text)';
    execute 'drop policy if exists student_media_delete on storage.objects';
    execute 'create policy student_media_delete on storage.objects for delete to authenticated using (bucket_id=''student-media'' and (storage.foldername(name))[1]=auth.uid()::text)';
  end if;
end $$;
